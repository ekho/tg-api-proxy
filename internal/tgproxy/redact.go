package tgproxy

import "regexp"

// tokenRe находит токен бота в любой строке. Формат токена — <bot_id>:<секрет>,
// где bot_id числовой, а секрет состоит из букв, цифр, дефисов и подчёркиваний.
var tokenRe = regexp.MustCompile(`bot(\d+):[A-Za-z0-9_-]+`)

// Redact заменяет секретную часть токена бота на REDACTED, сохраняя bot_id.
//
// Применяется ко всему, что покидает процесс: логам, атрибутам трейсов и лейблам
// метрик. Токен приходит от клиента в пути запроса, поэтому без маскирования
// чужие боевые токены осели бы в наблюдаемости платформы.
//
// bot_id сохраняется намеренно: он не секретен и нужен для диагностики.
func Redact(s string) string {
	return tokenRe.ReplaceAllString(s, "bot${1}:REDACTED")
}
