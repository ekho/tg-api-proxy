package tgproxy

// longPollMethod — имя метода long poll после нормализации в Method.
const longPollMethod = "getupdates"

// IsLongPoll сообщает, является ли путь вызовом getUpdates.
// Путь передаётся без query-строки.
//
// Опознание идёт через Method, а не собственным регэкспом: два почти одинаковых
// выражения рядом неизбежно разъезжаются и начинают отвечать по-разному на один
// и тот же путь. Регистронезависимость, без которой клиент обошёл бы серверный
// дедлайн запросом /GETUPDATES и снова упёрся бы в обрыв на ingress'е,
// приходит из нормализации в Method.
//
// Метод определяется по пути намеренно: параметры Bot API принимает четырьмя
// способами (query, form-urlencoded, JSON, multipart), а имя метода всегда
// лежит в URL. Это позволяет применить дедлайн, не буферизуя тело запроса.
func IsLongPoll(path string) bool {
	return Method(path) == longPollMethod
}
