package tgproxy

import (
	"regexp"
	"strings"
)

// methodNameRe ограничивает форму имени метода.
//
// Имя уходит в лейблы метрик и имена спанов, то есть туда, где кардинальность
// должна быть ограничена. Ограничения формы достаточно: до разбора пути запрос
// уже прошёл аутентификацию, поэтому влиять на лейбл могут только владельцы
// общего секрета, а не анонимы из интернета. Список всех ~100 методов Bot API
// поддерживать не нужно.
var methodNameRe = regexp.MustCompile(`^[A-Za-z]{1,32}$`)

// fileMethod — синтетическое имя для скачивания файла: у пути
// /file/bot<token>/<file_path> имени метода нет, а отличать его от вызовов API
// необходимо.
const fileMethod = "file"

// Method возвращает имя метода Bot API из пути в нижнем регистре.
// Путь передаётся без query-строки.
//
// Пустая строка означает «метод не определён»: путь не относится к Bot API,
// метод отсутствует, имеет недопустимую форму или за ним идут ещё сегменты.
//
// Требование «метод — последний сегмент» повторяет поведение прежнего
// longPollRe, который заканчивался на /?$: путь /bot<token>/getUpdates/extra
// Telegram не обслуживает, и считать его вызовом getUpdates нельзя — иначе к
// нему применился бы дедлайн long poll.
//
// File-ветка отдельно требует sepConsumed — литеральный "/" после токена.
// botPathRe матчит и без него, через нулевую ширину "$": это нужно
// ParseBotID, которому остаток пути не важен. Но для Method /file/bot<id>:
// <secret> без завершающего "/" — это не путь скачивания файла, а обрубленный
// URL, и он должен давать "", как раньше давал отдельный, ныне удалённый
// methodPathRe, требовавший "/" в обеих ветках.
//
// Не обрабатывается намеренно: путь с сырым '\n' в остатке file-ветки
// (например ".../a\nb") здесь даёт "file", хотя прежний methodPathRe с "$"
// без (?m) его не принимал ('.' не матчит '\n', так что "(.*)$" не мог дойти
// до конца строки). Через net/http этот случай недостижим: сервер отклоняет
// управляющие символы в URI раньше, чем запрос дойдёт до хендлера, — поэтому
// расхождение не устраняется, чтобы не усложнять код без практической пользы.
func Method(path string) string {
	_, isFile, rest, sepConsumed, ok := parseBotPath(path)
	if !ok {
		return ""
	}
	if isFile {
		if !sepConsumed {
			return ""
		}
		return fileMethod
	}
	// Если sepConsumed=false, совпадение дошло до конца строки через "$", а значит rest здесь пуст, и это отсеется проверкой ниже без отдельной проверки sepConsumed.
	name := strings.TrimSuffix(rest, "/")
	if !methodNameRe.MatchString(name) {
		return ""
	}
	return strings.ToLower(name)
}
